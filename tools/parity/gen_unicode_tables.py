"""Generate plumdeck-core's Unicode tables from this Python's own str methods.

    python tools/parity/gen_unicode_tables.py

Python 3.12 ships Unicode 15.0.0. The tables are taken from the interpreter
itself (str.casefold, str.lower, str.isalnum, the final-sigma rule) so the Rust
port matches it character for character, independent of the Rust std's newer
Unicode version. Normalization (NFC/NFKC) uses the unicode-normalization crate
pinned to the same Unicode version instead.
"""
from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

import parity_env

OUT = (parity_env.REPO_ROOT / "src-tauri" / "crates" / "plumdeck-core" / "src" / "compat"
       / "unicode_tables.rs")


def chars():
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp, chr(cp)


def ranges(codepoints):
    out = []
    for cp in codepoints:
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def rust_str(text: str) -> str:
    parts = []
    for ch in text:
        if ch in '"\\':
            parts.append("\\" + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            parts.append(ch)
        else:
            parts.append(f"\\u{{{ord(ch):x}}}")
    return '"' + "".join(parts) + '"'


def sigma_context(ch: str) -> tuple[bool, bool]:
    """(case_ignorable, cased) as Python's final-sigma rule sees them.

    For case-ignorable characters "cased" never matters: the rule skips them
    before it tests for a cased neighbour.
    """
    before = ("A" + ch + "Σ").lower()[-1]   # sigma after ch
    after = ("AΣ" + ch).lower()[1]          # sigma before ch
    if before == "σ":
        return False, False
    if after == "σ":
        return False, True
    return True, False


def main() -> None:
    casefold, lower, word, space, ignorable, cased = [], [], [], [], [], []
    word_re = re.compile(r"[^\W_]")
    for cp, ch in chars():
        folded = ch.casefold()
        if folded != ch:
            casefold.append((cp, folded))
        lowered = ch.lower()
        if lowered != ch:
            lower.append((cp, lowered))
        is_word = bool(word_re.match(ch))
        assert is_word == (ch.isalnum() and ch != "_"), hex(cp)
        if is_word:
            word.append(cp)
        if ch.isspace():
            space.append(cp)
        ign, cas = sigma_context(ch)
        if ign:
            ignorable.append(cp)
        if cas:
            cased.append(cp)

    lines = [
        "// @generated by tools/parity/gen_unicode_tables.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Python whitespace for str.split()/strip() (str.isspace).",
        "pub const SPACE: &[u32] = &[" + ", ".join(f"0x{cp:04x}" for cp in space) + "];",
        "",
    ]

    def emit_map(name, doc, items):
        lines.append(f"/// {doc}")
        lines.append(f"pub const {name}: &[(u32, &str)] = &[")
        for cp, text in items:
            lines.append(f"    (0x{cp:04x}, {rust_str(text)}),")
        lines.append("];")
        lines.append("")

    def emit_ranges(name, doc, items):
        lines.append(f"/// {doc}")
        lines.append(f"pub const {name}: &[(u32, u32)] = &[")
        for lo, hi in ranges(items):
            lines.append(f"    (0x{lo:04x}, 0x{hi:04x}),")
        lines.append("];")
        lines.append("")

    emit_map("CASEFOLD", "str.casefold() for every code point it changes.", casefold)
    emit_map("LOWER", "str.lower() for every code point it changes (context free).", lower)
    emit_ranges("WORD", "Code points matched by re `[^\\W_]` (str.isalnum()).", word)
    emit_ranges("CASE_IGNORABLE", "Case-ignorable code points for the final-sigma rule.", ignorable)
    emit_ranges("CASED", "Cased, non-ignorable code points for the final-sigma rule.", cased)
    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"{OUT}: casefold={len(casefold)} lower={len(lower)} word={len(ranges(word))} ranges "
          f"space={len(space)} ignorable={len(ranges(ignorable))} cased={len(ranges(cased))}")


if __name__ == "__main__":
    main()
