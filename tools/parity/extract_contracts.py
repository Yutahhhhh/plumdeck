"""Dump the Python backend's contracts into contracts/.

    python tools/parity/extract_contracts.py [--out contracts] [--keep-db DIR]

Writes:
  schema/v5.sql, schema/v5.columns.json  catalog of a fresh DB made by init_db()
  http/openapi.v5.json                   main.app.openapi()
  mcp/tools.v1.json                      tools/list as sent on the wire
  mcp/prompts.v1.json                    prompts/list as sent on the wire
  mcp/instructions.txt                   server instructions, verbatim

The backend is imported, never edited. DB_PATH and USER_DATA_DIR point into a
fresh temporary directory before any backend module is imported.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

import parity_env


def dump_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def schema_contract(db_path: Path, table_order: list[str]) -> tuple[str, dict]:
    import duckdb

    con = duckdb.connect(str(db_path), read_only=True)
    try:
        version = con.execute("SELECT version()").fetchone()[0]
        db = con.execute("SELECT current_database()").fetchone()[0]
        sequences = con.execute(
            """SELECT sequence_name, start_value, min_value, max_value, increment_by, cycle, sql
               FROM duckdb_sequences() WHERE database_name = ? AND schema_name = 'main'
               ORDER BY sequence_name""", [db]).fetchall()
        tables = dict(con.execute(
            """SELECT table_name, sql FROM duckdb_tables()
               WHERE database_name = ? AND schema_name = 'main'""", [db]).fetchall())
        indexes = con.execute(
            """SELECT index_name, table_name, sql FROM duckdb_indexes()
               WHERE database_name = ? AND schema_name = 'main' ORDER BY table_name, index_name""",
            [db]).fetchall()
        views = con.execute(
            """SELECT view_name, sql FROM duckdb_views()
               WHERE database_name = ? AND schema_name = 'main' AND NOT internal
               ORDER BY view_name""", [db]).fetchall()
        columns = con.execute(
            """SELECT table_name, column_name, column_index, data_type, is_nullable, column_default
               FROM duckdb_columns() WHERE database_name = ? AND schema_name = 'main'
               ORDER BY table_name, column_index""", [db]).fetchall()
        constraints = con.execute(
            """SELECT table_name, constraint_type, constraint_column_names
               FROM duckdb_constraints() WHERE database_name = ? AND schema_name = 'main'
               AND constraint_type IN ('PRIMARY KEY', 'UNIQUE')
               ORDER BY table_name, constraint_index""", [db]).fetchall()
    finally:
        con.close()

    ordered = [name for name in table_order if name in tables]
    ordered += sorted(name for name in tables if name not in ordered)

    lines = [
        "-- plumdeck schema v5, dumped from a fresh DB created by the Python backend's",
        f"-- init_db() with DuckDB {version}. Generated by tools/parity/extract_contracts.py;",
        "-- do not edit. Seed rows (schema_info.version) are not part of this file.",
        "",
    ]
    for _name, *_rest, sql in sequences:
        lines.append(sql.strip())
    lines.append("")
    for name in ordered:
        lines.append(tables[name].strip())
        lines.append("")
    for _index, _table, sql in indexes:
        if sql:
            lines.append(sql.strip())
    for _view, sql in views:
        lines.append(sql.strip())
    sql_text = "\n".join(lines).rstrip() + "\n"

    contract: dict = {
        "duckdb_version": version,
        "schema_version": 5,
        "sequences": [
            {"name": name, "start_value": start, "min_value": lo, "max_value": hi,
             "increment_by": inc, "cycle": cycle}
            for name, start, lo, hi, inc, cycle, _sql in sequences
        ],
        "tables": {},
    }
    for name in ordered:
        contract["tables"][name] = {"columns": [], "primary_key": [], "unique": []}
    for table, column, index, data_type, nullable, default in columns:
        contract["tables"][table]["columns"].append({
            "name": column, "ordinal": index, "type": data_type,
            "nullable": bool(nullable), "default": default,
        })
    for table, kind, names in constraints:
        key = "primary_key" if kind == "PRIMARY KEY" else "unique"
        if key == "primary_key":
            contract["tables"][table][key] = list(names)
        else:
            contract["tables"][table][key].append(list(names))
    return sql_text, contract


async def mcp_contract():
    from mcp_server.server import mcp

    tools = [tool.model_dump(mode="json", by_alias=True, exclude_none=True)
             for tool in await mcp.list_tools()]
    prompts = [prompt.model_dump(mode="json", by_alias=True, exclude_none=True)
               for prompt in await mcp.list_prompts()]
    return tools, prompts, mcp.instructions or ""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=parity_env.CONTRACTS_DIR)
    parser.add_argument("--keep-db", type=Path,
                        help="copy the freshly initialized DB file into this directory")
    args = parser.parse_args()

    sandbox = Path(tempfile.mkdtemp(prefix="plumdeck-contracts-"))
    user_data = sandbox / "ud"
    os.environ["USER_DATA_DIR"] = str(user_data)
    os.environ["DB_PATH"] = str(user_data / "plumdeck.duckdb")
    os.environ["PLUMDECK_LOG_DIR"] = str(user_data / "logs")
    parity_env.require_sandbox_env()
    parity_env.use_backend()
    os.chdir(sandbox)  # config.py reads ./.env when not frozen

    try:
        import main as backend_main
        from infra.database import connection
        from infra.database.schema import get_table_ddl

        connection.init_db()
        connection.checkpoint_db()
        connection.close_db()

        db_path = Path(connection.DB_PATH)
        sql_text, columns = schema_contract(db_path, list(get_table_ddl()))
        (args.out / "schema").mkdir(parents=True, exist_ok=True)
        (args.out / "schema" / "v5.sql").write_text(sql_text, encoding="utf-8")
        dump_json(args.out / "schema" / "v5.columns.json", columns)
        if args.keep_db:
            args.keep_db.mkdir(parents=True, exist_ok=True)
            shutil.copy2(db_path, args.keep_db / db_path.name)

        dump_json(args.out / "http" / "openapi.v5.json", backend_main.app.openapi())

        tools, prompts, instructions = asyncio.run(mcp_contract())
        dump_json(args.out / "mcp" / "tools.v1.json", tools)
        dump_json(args.out / "mcp" / "prompts.v1.json", prompts)
        (args.out / "mcp" / "instructions.txt").write_text(instructions, encoding="utf-8")

        print(f"tables={len(columns['tables'])} sequences={len(columns['sequences'])} "
              f"paths={len(backend_main.app.openapi()['paths'])} tools={len(tools)} "
              f"prompts={len(prompts)} duckdb={columns['duckdb_version']}")
    finally:
        shutil.rmtree(sandbox, ignore_errors=True)


if __name__ == "__main__":
    main()
