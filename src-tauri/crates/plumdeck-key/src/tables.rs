//! The key tables the frontend reads: contracts/key/keys.json and the
//! TypeScript module rendered from it (src/lib/keys.generated.ts). Both are
//! committed; `cargo run -p plumdeck-key --bin plumdeck-key-tables` rewrites
//! them and a test fails when they are stale.

use serde_json::{json, Value};

use crate::{relation, KeyId, Letter, Relation};

/// Path of the JSON table, relative to the repository root.
pub const JSON_PATH: &str = "contracts/key/keys.json";
/// Path of the generated TypeScript module, relative to the repository root.
pub const TS_PATH: &str = "src/lib/keys.generated.ts";

fn key_json(key: KeyId) -> Value {
    let (number, letter) = key.alphanumeric();
    json!({
        "id": key.index(),
        "pitch_class": key.pitch_class(),
        "minor": key.is_minor(),
        "classic": key.classic(),
        "alphanumeric": key.alphanumeric_text(),
        "number": number,
        "letter": if letter == Letter::A { "A" } else { "B" },
        "open_key": key.open_key(),
    })
}

/// contracts/key/keys.json.
pub fn keys_json() -> Value {
    let matrix: Vec<Vec<&str>> =
        KeyId::ALL.iter().map(|base| KeyId::ALL.iter().map(|candidate| relation(*base, *candidate).name()).collect()).collect();
    let levels: serde_json::Map<String, Value> = Relation::ALL
        .iter()
        .map(|relation| (relation.name().to_owned(), relation.traffic_light().map_or(Value::Null, |level| json!(level))))
        .collect();
    json!({
        "comment": "Generated by plumdeck-key (cargo run -p plumdeck-key --bin plumdeck-key-tables). Do not edit.",
        "version": 1,
        "default_notation": "alphanumeric",
        "notations": ["alphanumeric", "classic", "open_key"],
        "keys": KeyId::ALL.iter().map(|key| key_json(*key)).collect::<Vec<_>>(),
        "relations": {
            "names": Relation::ALL.iter().map(|relation| relation.name()).collect::<Vec<_>>(),
            "traffic_light": levels,
            "compatible": Relation::ALL.iter().filter(|r| r.is_compatible()).map(|r| r.name()).collect::<Vec<_>>(),
            "matrix": matrix,
        },
    })
}

/// The JSON file's text.
pub fn keys_json_text() -> String {
    serde_json::to_string_pretty(&keys_json()).expect("serializable") + "\n"
}

/// src/lib/keys.generated.ts: the same tables as typed constants.
pub fn keys_ts_text() -> String {
    let table = keys_json();
    let keys = serde_json::to_string(&table["keys"]).expect("keys");
    let names = serde_json::to_string(&table["relations"]["names"]).expect("names");
    let levels = serde_json::to_string(&table["relations"]["traffic_light"]).expect("levels");
    let matrix: Vec<String> = table["relations"]["matrix"]
        .as_array()
        .expect("matrix")
        .iter()
        .map(|row| format!("  {},", serde_json::to_string(row).expect("row")))
        .collect();
    format!(
        "// Generated by plumdeck-key from contracts/key/keys.json. Do not edit:\n\
         // cargo run -p plumdeck-key --bin plumdeck-key-tables (in src-tauri).\n\
         \n\
         export type KeyNotationId = \"alphanumeric\" | \"classic\" | \"open_key\";\n\
         export const DEFAULT_KEY_NOTATION: KeyNotationId = \"alphanumeric\";\n\
         \n\
         export type KeyEntry = {{\n\
         \x20 id: number;\n\
         \x20 pitch_class: number;\n\
         \x20 minor: boolean;\n\
         \x20 classic: string;\n\
         \x20 alphanumeric: string;\n\
         \x20 number: number;\n\
         \x20 letter: \"A\" | \"B\";\n\
         \x20 open_key: string;\n\
         }};\n\
         \n\
         /** Indexed by key id: pitch class + 12 for minor. */\n\
         export const KEYS: readonly KeyEntry[] = {keys};\n\
         \n\
         export type KeyRelation = \"same\" | \"adjacent\" | \"relative\" | \"diagonal\" | \"plus2\" | \"semitone\" | \"other\";\n\
         export const KEY_RELATIONS: readonly KeyRelation[] = {names};\n\
         \n\
         /** Traffic Light level per relation: 1 green, 2 yellow, null none. */\n\
         export const TRAFFIC_LIGHT: Readonly<Record<KeyRelation, 1 | 2 | null>> = {levels};\n\
         \n\
         /** RELATION_MATRIX[base][candidate]. */\n\
         export const RELATION_MATRIX: readonly (readonly KeyRelation[])[] = [\n{}\n];\n\
         \n\
         export function keyRelation(base: number, candidate: number): KeyRelation {{\n\
         \x20 return RELATION_MATRIX[base]?.[candidate] ?? \"other\";\n\
         }}\n\
         \n\
         export function formatKeyId(id: number, notation: KeyNotationId): string {{\n\
         \x20 const key = KEYS[id];\n\
         \x20 return key ? key[notation] : \"\";\n\
         }}\n",
        matrix.join("\n")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_file(path: &str) -> String {
        let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../../..");
        std::fs::read_to_string(format!("{root}/{path}")).unwrap_or_else(|error| panic!("read {path}: {error}"))
    }

    #[test]
    fn committed_tables_are_current() {
        assert_eq!(repo_file(JSON_PATH), keys_json_text(), "run plumdeck-key-tables");
        assert_eq!(repo_file(TS_PATH), keys_ts_text(), "run plumdeck-key-tables");
    }

    #[test]
    fn json_lists_every_key() {
        let table = keys_json();
        assert_eq!(table["keys"].as_array().unwrap().len(), 24);
        assert_eq!(table["keys"][21]["alphanumeric"], "8A");
        assert_eq!(table["relations"]["matrix"][9][18], "relative", "A major and F#m");
    }
}
